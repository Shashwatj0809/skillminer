/**
 * Skill builder.
 *
 * Emits skills in the open SKILL.md convention (YAML frontmatter with
 * `name` + `description`, markdown body) — the format Claude Code loads
 * from .claude/skills/, and plain enough for any other agent to consume
 * as context. One directory per skill:
 *
 *   <out>/
 *     global/
 *       user-preferences/SKILL.md
 *       tech-stack/SKILL.md
 *       working-style/SKILL.md
 *     repos/
 *       <repo-name>/project-context/SKILL.md
 *
 * `improve` mode merges new bullets into existing skills instead of
 * overwriting, so skills accumulate and refine over time.
 */
import fs from "node:fs";
import path from "node:path";
import { redact } from "./redact.js";

const GENERATED_NOTE =
  "<!-- generated by skillminer — re-run `skillminer improve` to refine. Bullets you add by hand are preserved. -->";

function frontmatter(name, description) {
  return `---\nname: ${name}\ndescription: ${description}\n---\n`;
}

function bulletize(items, max = 40) {
  return items.slice(0, max).map((i) => `- ${typeof i === "string" ? i : i.text}`);
}

export function buildGlobalSkills(analysis, { generatedAt } = {}) {
  const skills = [];
  const stamp = generatedAt ?? new Date().toISOString().slice(0, 10);

  if (analysis.requirements.length || analysis.preferences.length || analysis.corrections.length) {
    const body = [
      frontmatter(
        "user-preferences",
        "Standing requirements and preferences this user has expressed across past agent sessions. Apply them by default in every task."
      ),
      GENERATED_NOTE,
      `\n# User preferences\n`,
      `_Mined from ${analysis.behavior.totalConversations} conversations, updated ${stamp}._\n`,
    ];
    if (analysis.requirements.length) {
      body.push(`\n## Standing requirements\n`, ...bulletize(analysis.requirements));
    }
    if (analysis.preferences.length) {
      body.push(`\n## Preferences\n`, ...bulletize(analysis.preferences));
    }
    if (analysis.corrections.length) {
      body.push(
        `\n## Past corrections (things that went wrong before — avoid repeating)\n`,
        ...bulletize(analysis.corrections, 20)
      );
    }
    skills.push({ dir: path.join("global", "user-preferences"), content: body.join("\n") + "\n" });
  }

  if (analysis.stack.length) {
    const body = [
      frontmatter(
        "tech-stack",
        "Technologies this user actually works with, ranked by how often they come up. Default to these when choices are open."
      ),
      GENERATED_NOTE,
      `\n# Tech stack\n`,
      `\n| Technology | Mentions |\n|---|---|`,
      ...analysis.stack.slice(0, 25).map((s) => `| ${s.tech} | ${s.mentions} |`),
    ];
    skills.push({ dir: path.join("global", "tech-stack"), content: body.join("\n") + "\n" });
  }

  const b = analysis.behavior;
  if (b.totalUserMessages > 0) {
    const peakHour = b.activeHours.indexOf(Math.max(...b.activeHours));
    const traits = [];
    if (b.asksForPlanning / b.totalUserMessages > 0.08) traits.push("- Likes a plan or architecture sketch before implementation starts.");
    if (b.asksForTests / b.totalUserMessages > 0.08) traits.push("- Expects tests to be written or run as part of the work.");
    if (b.asksForExplanation / b.totalUserMessages > 0.15) traits.push("- Wants reasoning explained, not just results delivered.");
    if (b.givesUrls / b.totalUserMessages > 0.15) traits.push("- Often shares reference links — read them before acting.");
    if (b.avgUserMessageChars > 400) traits.push("- Writes long, detailed prompts — the full message usually contains several distinct asks; address all of them.");
    else if (b.avgUserMessageChars < 120) traits.push("- Writes terse prompts — infer intent from context rather than asking many clarifying questions.");

    const body = [
      frontmatter(
        "working-style",
        "How this user communicates and likes to work with agents, derived from message patterns across providers."
      ),
      GENERATED_NOTE,
      `\n# Working style\n`,
      `\n- Sessions analyzed: ${b.totalConversations} across ${Object.keys(b.providers).join(", ")}`,
      `- User messages: ${b.totalUserMessages} (avg ${b.avgUserMessageChars} chars)`,
      `- Most active around ${String(peakHour).padStart(2, "0")}:00 local time`,
      ...(traits.length ? [`\n## Traits\n`, ...traits] : []),
    ];
    skills.push({ dir: path.join("global", "working-style"), content: body.join("\n") + "\n" });
  }

  return skills;
}

export function buildRepoSkill(repoPath, analysis, { generatedAt } = {}) {
  const repoName = path.basename(repoPath) || "root";
  const stamp = generatedAt ?? new Date().toISOString().slice(0, 10);
  const safeRepoPath = redact(repoPath);

  const sections = [
    frontmatter(
      `project-${slug(repoName)}`,
      `Requirements and context for the ${repoName} project, mined from past agent sessions in that repo. Use when working in ${safeRepoPath}.`
    ),
    GENERATED_NOTE,
    `\n# Project: ${repoName}\n`,
    `_Path: \`${safeRepoPath}\` · ${analysis.behavior.totalConversations} sessions analyzed · updated ${stamp}._\n`,
  ];
  if (analysis.requirements.length) {
    sections.push(`\n## Requirements stated for this project\n`, ...bulletize(analysis.requirements));
  }
  if (analysis.preferences.length) {
    sections.push(`\n## Preferences in this project\n`, ...bulletize(analysis.preferences));
  }
  if (analysis.corrections.length) {
    sections.push(`\n## Corrections made here (avoid repeating)\n`, ...bulletize(analysis.corrections, 15));
  }
  if (analysis.stack.length) {
    sections.push(
      `\n## Stack seen in this project\n`,
      analysis.stack.slice(0, 15).map((s) => `\`${s.tech}\``).join(" · ")
    );
  }

  const hasContent = analysis.requirements.length || analysis.preferences.length || analysis.corrections.length;
  if (!hasContent) return null;

  return {
    dir: path.join("repos", slug(repoName), "project-context"),
    repoPath,
    content: sections.join("\n") + "\n",
  };
}

export function slug(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60) || "unnamed";
}

/**
 * Write skills to disk. If a SKILL.md already exists, merge: keep every
 * existing bullet line (including hand-added ones), append new ones under
 * the matching section. Returns list of written paths.
 */
export function writeSkills(skills, outDir) {
  const written = [];
  for (const skill of skills) {
    if (!skill) continue;
    const dir = path.join(outDir, skill.dir);
    fs.mkdirSync(dir, { recursive: true });
    const file = path.join(dir, "SKILL.md");
    let content = skill.content;
    if (fs.existsSync(file)) {
      content = mergeSkill(fs.readFileSync(file, "utf8"), skill.content);
    }
    fs.writeFileSync(file, content);
    written.push(file);
  }
  return written;
}

/** Merge old and new skill markdown: union of bullet lines per section, new prose wins. */
export function mergeSkill(oldMd, newMd) {
  const oldBullets = extractBulletsBySection(oldMd);
  const newSections = splitSections(newMd);

  const out = [];
  for (const sec of newSections) {
    out.push(sec.header);
    const seen = new Set();
    const lines = [];
    for (const line of sec.lines) {
      if (line.startsWith("- ")) {
        const k = normBullet(line);
        if (!seen.has(k)) {
          seen.add(k);
          lines.push(line);
        }
      } else {
        lines.push(line);
      }
    }
    // carry over old bullets not present in the new version (incl. hand-added)
    for (const old of oldBullets.get(sec.key) ?? []) {
      const k = normBullet(old);
      if (!seen.has(k)) {
        seen.add(k);
        lines.push(old);
      }
    }
    out.push(...lines);
  }
  return out.join("\n");
}

function splitSections(md) {
  const lines = md.split("\n");
  const sections = [];
  let current = { key: "__head__", header: null, lines: [] };
  for (const line of lines) {
    if (/^#{1,3} /.test(line)) {
      if (current.header !== null || current.lines.length) sections.push(current);
      current = { key: line.replace(/^#+ /, "").trim().toLowerCase(), header: line, lines: [] };
    } else {
      current.lines.push(line);
    }
  }
  sections.push(current);
  // normalize: first section header may be null (frontmatter block)
  return sections.map((s) => ({ ...s, header: s.header ?? s.lines.shift() ?? "" }));
}

function extractBulletsBySection(md) {
  const map = new Map();
  for (const sec of splitSections(md)) {
    map.set(
      sec.key,
      sec.lines.filter((l) => l.startsWith("- "))
    );
  }
  return map;
}

function normBullet(line) {
  return line.toLowerCase().replace(/[^a-z0-9 ]/g, "").trim().slice(0, 120);
}
